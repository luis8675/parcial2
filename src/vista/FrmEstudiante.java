    public void cargarEstudiantes() {
        modeloTabla.setRowCount(0);
        for (Estudiante est : controlador.obtenerEstudiante()) {
            modeloTabla.addRow(new Object[]{
                est.getIdEstudiante(),
                est.getFirstName(),
                est.getSecondName(),
                est.getLastName(),
                est.getCarnet(),
                est.getCarrera(),
                est.getDireccion(),
                est.getTelefono(),
                est.getFechaNacimiento(),
                est.getFechaIngreso(),
                est.getCuotaMensual()
            });
        }
    }
    
    
