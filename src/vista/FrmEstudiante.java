    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        String idEstudiante = JOptionPane.showInputDialog("ID del Estudiant a Actualizar:");
        if (idEstudiante != null && !idEstudiante.isEmpty()) {
            try {
                controlador.actualizarEstudiante(                       
                        Integer.parseInt(idEstudiante),
                        txtNombre1.getText(),
                        txtNombre2.getText(),
                        txtApellido.getText(),
                        txtCarnet.getText(),
                        txtCarrera.getText(),
                        txtDireccion.getText(),
                        Integer.parseInt(txtTelefono.getText()),
                        txtFechaNacimiento.getText(),
                        txtFechaingreso.getText()
                );
                
                JOptionPane.showMessageDialog(this, "Cliente actualizado correctamente");
                cargarEstudiantes();
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Error en el formato de los números");
            }
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

        String idStr = JOptionPane.showInputDialog("ID del Estudiante a Eliminar:");
        if (idStr != null && !idStr.isEmpty()) {
            controlador.eliminarEstudiante(Integer.parseInt(idStr));
            JOptionPane.showMessageDialog(this, "Estudiante eliminado correctamente");
            cargarEstudiantes();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

